const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=name=>fs.readFileSync('static/'+name,'utf8');
const source=read('crm-followup-contact.js'),inbox=read('crm-inbox.js');
const ctx={window:{}};vm.createContext(ctx);vm.runInContext(source,ctx);
const checked=ctx.window.crmFollowupReplyChecked;
assert.equal(checked(true,{paused:false}),true);
assert.equal(checked(true,{paused:false},null),true);
assert.equal(checked(true,{paused:false},false),false);
assert.equal(checked(true,{paused:true},true),false);
assert.equal(checked(false,{paused:false}),false);
assert.equal(checked(true,null),false);
assert.match(inbox,/id="followupReplyRequested" checked/);
assert.match(inbox,/followupReplyOverride=null;media.clear/);
assert.match(source,/lead.followup_contact\?\.revision>value.revision/);
assert.match(source,/pane.isConnected && active\(\)/);
assert.match(source,/textContent=message/);
assert.ok(read('crm.js').includes('followupContacts.mount(followupControl,l'));
assert.ok(read('crm.html').includes('/crm-followup-contact.js?v=2'));
console.log('Follow-up contact UI: default checked, manual override, persistent pause, fail-closed loading and stale-scope guards OK');
