const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const read=name=>fs.readFileSync(path.join(__dirname,"../static",name),"utf8");
const inbox=read("crm-inbox.js"),css=read("crm-shell.css"),html=read("crm.html"),crm=read("crm.js");
const context={};vm.createContext(context);
const start=inbox.indexOf("  function waitingTime(");
assert.ok(start>=0);
vm.runInContext(inbox.slice(start,inbox.indexOf("  function waitingTimer(",start))+";format=waitingTime;",context);
for(const [seconds,expected] of [[0,"00:00"],[59,"00:59"],[61,"01:01"],[3601,"01:00:01"],[90061,"1d 01h"]])assert.equal(context.format(seconds),expected);
assert.match(inbox,/server_time/);
assert.match(inbox,/setInterval\(updateTimers,1000\)/);
assert.match(inbox,/Sem resposta/);
for(const mode of ["dashboard","board","inbox","campaigns","channels","templates"])assert.ok(html.includes(`data-mode="${mode}"`));
assert.match(css,/height:100dvh/);
assert.match(css,/data-crm-mode=inbox\]>\.crmContent\{padding:0!important/);
assert.match(crm,/inbox\.setFilter\("waiting"\)/);
assert.match(read("crm-dashboard.js"),/d\.operators!==null/);
assert.match(read("crm-shell.js"),/aria-expanded/);
console.log("CRM workspace: full viewport, navigation, dashboard waiting action and timer formatting OK");
