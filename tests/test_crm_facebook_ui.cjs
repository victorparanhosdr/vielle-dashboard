const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const read=file=>fs.readFileSync(path.join(__dirname,'../static',file),'utf8');
new vm.Script(read('crm-facebook.js'));
const main=read('crm.js'),html=read('crm.html');
assert.ok(main.includes("state.mode==='facebook' && !state.data.can_manage"));
assert.ok(html.includes('data-mode="facebook"'));
assert.ok(html.includes('/crm-facebook.js?v=1'));
const ctx={window:{}};vm.createContext(ctx);vm.runInContext(read('crm-facebook.js'),ctx);
const root={isConnected:true,innerHTML:''},calls=[],opened=[];
const state={doctor:'a',data:{doctors:[{id:'a',name:'Doutor A'}]}};
const data={connected:true,account_id:'800',synced_at:10000,pending:1,campaigns:[{campaign_id:'456',name:'Campanha <A>',status:'ACTIVE',identified:1}],leads:[]};
const api=async(action,payload,query)=>{calls.push({action,payload,query});return {...data,leads:query.campaign?[{id:'lead-a',name:'Cliente Exemplo',pipeline:'Organico',stage:'Novo'}]:[]};};
const esc=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
const view=ctx.window.createCrmFacebook({state,api,esc,icon:()=>'',icons:()=>{},profile:id=>opened.push(id)});
const click=(selector,dataset={})=>root.onclick({target:{closest:value=>value===selector?{dataset}:null}});
(async()=>{
  await view.mount(root);
  assert.ok(root.innerHTML.includes('Campanha &lt;A>'));
  assert.ok(root.innerHTML.includes('Leads identificados'));
  click('[data-facebook-campaign]',{facebookCampaign:'456'});
  await new Promise(resolve=>setImmediate(resolve));
  assert.equal(calls.at(-1).query.campaign,'456');
  assert.ok(root.innerHTML.includes('Cliente Exemplo'));
  click('[data-facebook-lead]',{facebookLead:'lead-a'});
  assert.deepEqual(opened,['lead-a']);
  click('[data-facebook-sync]');await new Promise(resolve=>setImmediate(resolve));
  assert.equal(calls.at(-1).action,'facebook-sync');
  view.unmount();assert.equal(root.onclick,null);
  console.log('Facebook integration UI, campaign selection and scoped sync passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
